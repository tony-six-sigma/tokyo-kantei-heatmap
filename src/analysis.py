def yoy_pct(cur, prev):
    if prev <= 0:
        return float("nan")
    return (cur / prev - 1) * 100

def max_sqm_for_100m(price_per_tsubo_man):
    """¥100M / (¥/坪 × 10000 / 3.306) ㎡"""
    return 33060 / price_per_tsubo_man

def analyze():
    rows = []
    for line, stations in DATA.items():
        for entry in stations:
            station, p, age, sqm, p1, age1, sqm1, p2, age2, sqm2 = entry
            yoy_1 = yoy_pct(p, p1)
            yoy_2 = yoy_pct(p, p2)
            cagr_2 = ((p / p2) ** 0.5 - 1) * 100 if p2 > 0 else float("nan")
            max_sqm = max_sqm_for_100m(p)
            est_2br_price = p * 60 / 3.306 / 100  # 60㎡ 2LDK in 百万円
            rows.append({
                "line": line,
                "station": station,
                "p_now": p,
                "p_1y": p1,
                "p_2y": p2,
                "yoy_1y": yoy_1,
                "yoy_2y": yoy_2,
                "cagr_2y": cagr_2,
                "avg_sqm": sqm,
                "avg_age": age,
                "max_sqm_100m": max_sqm,
                "est_60sqm_price_M": est_2br_price,
            })
    return rows

def filter_affordable_2br(rows, min_sqm_for_100m=55, max_age=40):
    """We want stations where a typical 2BR (≥55㎡) fits under ¥100M, and the
    market hasn't aged out (avg_age ≤ 40)."""
    return [r for r in rows if r["max_sqm_100m"] >= min_sqm_for_100m
            and r["avg_age"] <= max_age]

def rank_for_capgains(rows):
    """Composite score:
    - 60% weight: 2yr cagr (sustained appreciation)
    - 40% weight: 1yr yoy (momentum)
    - Penalty: avg_age > 35 (aging stock = harder resale)
    """
    scored = []
    for r in rows:
        cagr = r["cagr_2y"]
        yoy = r["yoy_1y"]
        if cagr != cagr or yoy != yoy:  # NaN check
            continue
        score = 0.6 * cagr + 0.4 * yoy
        if r["avg_age"] > 35:
            score -= 2  # mild penalty
        scored.append((score, r))
    scored.sort(key=lambda x: -x[0])
    return scored

